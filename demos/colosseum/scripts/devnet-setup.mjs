import {createHash} from 'node:crypto';
import {chmod, lstat, mkdir, open, readFile, writeFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {homedir} from 'node:os';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {Connection, Keypair, PublicKey} from '@solana/web3.js';
import {GENESIS, RPC} from '../src/solana.mjs';
import {resolveSolanaCli} from './solana-cli.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const demo = resolve(here, '..');
const local = resolve(demo, '.local');
const payerFile = resolve(local, 'payer.json');
const sbfOutput = resolve(local, 'sbf');
const programFile = resolve(sbfOutput, 'vitalid_permission-keypair.json');
const markerFile = resolve(local, 'generated-keys.json');
const deploymentFile = resolve(local, 'deployment.json');
const artifact = resolve(sbfOutput, 'vitalid_permission.so');
const INSTALL_MARKER = 'vitalid-colosseum-disposable-devnet-keys-v1';
const CHILD_ENV = {HOME: homedir(), PATH: '/usr/bin:/bin', LANG: 'C.UTF-8'};
let solanaCli;

function runSolana(args, timeout = 120000) {
  const result = spawnSync(solanaCli, args, {
    cwd: demo,
    encoding: 'utf8',
    timeout,
    env: CHILD_ENV,
  });
  if (result.error) throw new Error(`Solana CLI could not run: ${result.error.message}`);
  if (result.status !== 0) {
    const detail = (result.stderr || result.stdout || '').trim().slice(-800);
    throw new Error(`Solana CLI ${args[0]} failed (exit ${result.status}): ${detail || 'no diagnostic output'}`);
  }
  return `${result.stdout ?? ''}\n${result.stderr ?? ''}`;
}

async function exists(path) {
  try {
    await lstat(path);
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}

async function loadKeypair(path) {
  const file = await lstat(path);
  if (file.isSymbolicLink() || !file.isFile() || (file.mode & 0o077) !== 0) {
    throw new Error(`Local key file must be a private regular file: ${path}`);
  }
  return Keypair.fromSecretKey(Uint8Array.from(JSON.parse(await readFile(path, 'utf8'))));
}

async function createLocalKeys() {
  const localExists = await exists(local);
  if (!localExists) await mkdir(local, {mode: 0o700});
  const directory = await lstat(local);
  if (directory.isSymbolicLink() || !directory.isDirectory() || (directory.mode & 0o077) !== 0) {
    throw new Error('The demo .local directory must be a private, non-symlink directory.');
  }
  const files = [payerFile, markerFile, deploymentFile, programFile];
  const present = await Promise.all(files.map(exists));
  if (present[2]) throw new Error('A deployment receipt already exists; refusing an automatic program upgrade.');
  if (present[0] || present[1] || present[3]) {
    if (!present[0] || !present[1]) {
      throw new Error('Partial .local key material exists; refusing to overwrite it.');
    }
    const marker = JSON.parse(await readFile(markerFile, 'utf8'));
    if (marker.generatedBy !== INSTALL_MARKER) {
      throw new Error('Existing .local keys were not generated by this setup script; refusing to use them.');
    }
    const payer = await loadKeypair(payerFile);
    if (marker.payer !== payer.publicKey.toBase58()) {
      throw new Error('Local payer key does not match its setup marker.');
    }
    if (present[3]) await loadKeypair(programFile);
    return {payer};
  }

  const payer = Keypair.generate();
  const filesToWrite = [
    [payerFile, JSON.stringify(Array.from(payer.secretKey))],
    [markerFile, JSON.stringify({
      generatedBy: INSTALL_MARKER,
      payer: payer.publicKey.toBase58(),
    })],
  ];
  process.umask(0o077);
  for (const [path, content] of filesToWrite) {
    const handle = await open(path, 'wx', 0o600);
    try {
      await handle.writeFile(content);
    } finally {
      await handle.close();
    }
    await chmod(path, 0o600);
  }
  return {payer};
}

async function main() {
  if (process.argv.slice(2).some(argument => argument !== '--prepare-only')) {
    throw new Error('Only the optional --prepare-only argument is supported.');
  }
  const prepareOnly = process.argv.includes('--prepare-only');
  if (prepareOnly) {
    const {payer} = await createLocalKeys();
    process.stdout.write(`Disposable devnet keys prepared under ${local}\n`);
    process.stdout.write(`Payer public key: ${payer.publicKey.toBase58()}\n`);
    process.stdout.write('Build the SBF artifact with --sbf-out-dir .local/sbf before deployment.\n');
    return;
  }

  solanaCli = await resolveSolanaCli();
  const cliVersion = runSolana(['--version']).trim().split('\n')[0];
  const programBytes = await readFile(artifact);
  if (!programBytes.length) throw new Error('SBF program artifact is empty.');
  const artifactSha256 = createHash('sha256').update(programBytes).digest('hex');
  const {payer} = await createLocalKeys();
  const program = await loadKeypair(programFile);
  const connection = new Connection(RPC, {
    commitment: 'confirmed',
    disableRetryOnRateLimit: true,
    fetch: (url, options) => fetch(url, {...options, signal: AbortSignal.timeout(12000)}),
  });
  if (await connection.getGenesisHash() !== GENESIS) throw new Error('Configured RPC is not official Solana devnet.');
  const existing = await connection.getAccountInfo(program.publicKey, 'confirmed');
  if (existing) throw new Error('Program address already exists; refusing an automatic upgrade.');

  let balance = await connection.getBalance(payer.publicKey, 'confirmed');
  if (balance < 1_000_000_000) {
    runSolana([
      'airdrop', '2', payer.publicKey.toBase58(),
      '--url', RPC, '--keypair', payerFile, '--commitment', 'confirmed',
    ]);
    balance = await connection.getBalance(payer.publicKey, 'confirmed');
  }
  if (balance < 1_000_000_000) throw new Error('Devnet faucet balance is below the 1 SOL deployment floor.');
  if (await connection.getGenesisHash() !== GENESIS) throw new Error('Devnet genesis changed before deployment.');

  const output = runSolana([
    'program', 'deploy', artifact,
    '--url', RPC,
    '--keypair', payerFile,
    '--program-id', programFile,
    '--upgrade-authority', payerFile,
    '--commitment', 'confirmed',
    '--max-sign-attempts', '2',
    '--use-rpc',
  ], 180000);
  const deployedProgram = output.match(/Program Id:\s*([1-9A-HJ-NP-Za-km-z]+)/)?.[1];
  const deploySignature = output.match(/Signature:\s*([1-9A-HJ-NP-Za-km-z]+)/)?.[1];
  if (deployedProgram !== program.publicKey.toBase58() || !deploySignature) {
    throw new Error('Deployment output did not include the expected program and transaction signature.');
  }
  const programAccount = await connection.getAccountInfo(new PublicKey(deployedProgram), 'confirmed');
  if (!programAccount?.executable) throw new Error('Deployment did not produce a confirmed executable program account.');
  const authority = payer.publicKey.toBase58();
  const record = {
    network: 'devnet',
    rpc: RPC,
    genesis: GENESIS,
    program: deployedProgram,
    payer: authority,
    upgradeAuthority: authority,
    deploySignature,
    artifactSha256,
    artifactBytes: programBytes.length,
    cliVersion,
    deployedAt: new Date().toISOString(),
    confirmedExecutable: true,
  };
  await writeFile(deploymentFile, `${JSON.stringify(record, null, 2)}\n`, {mode: 0o600, flag: 'wx'});
  process.stdout.write(`${JSON.stringify(record, null, 2)}\n`);
  process.stdout.write(`Private fee-payer file: ${payerFile}\n`);
  process.stdout.write('Upgrade authority remains the disposable local payer; it was not removed.\n');
}

main().catch(error => {
  process.stderr.write(`Devnet setup blocked: ${error.message}\n`);
  process.exitCode = 1;
});
