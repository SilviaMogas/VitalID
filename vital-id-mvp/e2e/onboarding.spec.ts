import {expect,test} from "@playwright/test";
test.use({viewport:{width:390,height:844}});
for(const lang of ["en","ar"] as const){
  test(`${lang}: purpose → consent → selected fictional pack → preview → recipient → revoke`,async({page,context},info)=>{
    await page.addInitScript(l=>localStorage.setItem("vitalid.lang",JSON.stringify(l)),lang);
    await page.goto("/onboarding");
    const ar=lang==="ar";
    await expect(page.locator("html")).toHaveAttribute("dir",ar?"rtl":"ltr");
    await page.getByRole("radio").nth(2).check();
    await page.getByRole("button",{name:ar?"متابعة":"Continue",exact:true}).click();
    const consent=page.getByRole("button",{name:ar?"أوافق وأتابع":"Agree and continue"});
    await expect(consent).toBeDisabled();
    await page.getByTestId("pack-essential").check();await consent.click();
    await page.getByTestId("pack-start-demo").click();
    await expect(page.getByTestId("pack-review")).toBeDisabled();
    await page.getByRole("checkbox").nth(0).check();
    await page.getByRole("checkbox").last().check();
    await page.getByTestId("pack-review").click();
    await expect(page.getByTestId("pack-preview").locator("[data-testid^=pack-field-]")).toHaveCount(1);
    await expect(page.getByTestId("pack-preview").locator("[data-testid^=pack-document-]")).toHaveCount(1);
    await expect(page.getByTestId("pack-preview")).toContainText("Cedar Example Insurance (fictional)");
    await expect(page.getByTestId("pack-preview")).not.toContainText("6h 22m");
    const before=await page.getByTestId("pack-preview").innerText();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:info.outputPath(`pack-preview-${lang}.png`),fullPage:true});
    await page.getByTestId("pack-confirm").click();
    await page.waitForURL(/share\/issued/);
    const url=await page.locator(".card p.break-all").innerText();
    const recipient=await context.newPage();await recipient.goto(url);
    await expect(recipient.getByTestId("pack-preview")).toHaveText(before,{useInnerText:true});
    const documentLink=recipient.getByRole("link",{name:ar?"تنزيل المستند":"Download document"});
    const href=await documentLink.getAttribute("href");
    expect((await page.request.get(href!)).status()).toBe(200);
    await expect(page.getByTestId("share-audit")).toContainText(ar?"تم الإنشاء":"Created");
    await expect(page.getByTestId("share-audit")).toContainText(ar?"تم الفتح":"Opened",{timeout:10000});
    page.once("dialog",d=>d.accept());
    await page.getByRole("button",{name:ar?"إلغاء الوصول الآن":"Revoke access now"}).click();
    await expect(recipient.getByTestId("state-revoked")).toBeVisible({timeout:10000});
    expect((await page.request.get(href!)).status()).toBe(403);
    await expect(page.getByTestId("share-audit")).toContainText(ar?"تم الإلغاء":"Revoked");
  });
}
test("manual edits and removal persist; optional WHOOP is never fetched without consent",async({page})=>{
  await page.addInitScript(()=>localStorage.setItem("vitalid.lang",JSON.stringify("en")));
  let imports=0;
  await page.route("**/api/onboarding/config",r=>r.fulfill({json:{whoopConfigured:true,persistentShares:true}}));
  await page.route("**/api/whoop/signals**",r=>{imports++;return r.fulfill({json:{configured:true,connected:false}});});
  await page.goto("/onboarding");
  await page.getByRole("button",{name:"Continue",exact:true}).click();
  await page.getByTestId("pack-essential").check();
  await page.getByRole("button",{name:"Agree and continue"}).click();
  await expect(page.getByRole("button",{name:"Connect / import WHOOP"})).toBeDisabled();expect(imports).toBe(0);
  await page.getByTestId("pack-start-manual").click();
  await page.getByRole("button",{name:"Add a field"}).click();
  await page.getByLabel("Field name", {exact:true}).fill("My medication");
  await page.getByLabel("Value",{exact:true}).fill("Entered by me");
  await page.getByRole("checkbox").check();
  await page.getByTestId("pack-recipient").fill("Dr Example");
  await page.reload();
  await expect(page.getByLabel("Value",{exact:true})).toHaveValue("Entered by me");
  await page.getByLabel("Value",{exact:true}).fill("Corrected by me");
  await page.getByRole("button",{name:"Remove My medication"}).click();
  await expect(page.getByTestId("pack-review")).toBeDisabled();
  await page.reload();await expect(page.getByLabel("Value",{exact:true})).toHaveCount(0);
  expect(imports).toBe(0);
});
