export type DictKey = keyof (typeof dict)["en"];

export const dictionaries: Record<Lang, Record<DictKey, string>> = dict;

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function viewsLabel(
  n: number,
  lang: Lang,
  t: (key: DictKey, vars?: Record<string, string | number>) => string
): string {
  if (n === 0) return t("share.views.none");
  const key: DictKey =
    lang === "ar"
      ? n === 1
        ? "share.views.one"
        : n === 2
          ? "share.views.two"
          : n <= 10
            ? "share.views.few"
            : "share.views.count"
      : n === 1
        ? "share.views.one"
        : "share.views.count";
  return t(key, { n });
}
