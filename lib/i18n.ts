export const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, ar };

export function translate(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  let text: string = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function formatNumber(locale: Locale, value: number, decimals = 0): string {
  return new Intl.NumberFormat(locale === "ar" ? "ar-AE" : "en-US", {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  }).format(value);
}

export function formatDate(locale: Locale, iso: string, opts?: Intl.DateTimeFormatOptions): string {
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-AE" : "en-GB", {
    day: "numeric",
    month: "short",
    ...opts,
  }).format(new Date(iso));
}

/** Translates an ISO nationality code; falls back to the raw text for free-form entries. */
export function nationalityLabel(
  nationality: string,
  t: (key: TranslationKey) => string,
): string {
  const key = `vitalId.nationality.${nationality}` as TranslationKey;
  const translated = t(key);
  return translated === key ? nationality || "—" : translated;
}
